use leptos::prelude::*;
use web_sys::window;

const LANG_KEY: &str = "ks_lang";

/// Supported UI languages. `En` is the default; `Vi` is Vietnamese.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Language {
    En,
    Vi,
}

impl Language {
    /// Short storage/HTML code, e.g. "en" / "vi".
    pub fn code(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Vi => "vi",
        }
    }

    /// Human label shown on the switcher button.
    pub fn label(self) -> &'static str {
        match self {
            Language::En => "EN",
            Language::Vi => "VI",
        }
    }

    fn from_code(code: &str) -> Option<Self> {
        match code {
            "en" => Some(Language::En),
            "vi" => Some(Language::Vi),
            _ => None,
        }
    }
}

/// Reactive language context, shared app-wide. `Copy` so it can be captured
/// freely inside view closures.
#[derive(Clone, Copy)]
pub struct I18nContext {
    pub lang: RwSignal<Language>,
}

impl I18nContext {
    /// Reactively translate `key` into the currently-selected language.
    /// Reads the `lang` signal, so any view that calls this inside a closure
    /// re-renders when the language changes. Unknown keys fall back to the key.
    pub fn t(&self, key: &str) -> &'static str {
        translate(self.lang.get(), key)
    }

    /// Switch language, persist the choice, and update `<html lang>`.
    pub fn set(&self, lang: Language) {
        self.lang.set(lang);
        if let Some(storage) = window().and_then(|w| w.local_storage().ok().flatten()) {
            let _ = storage.set_item(LANG_KEY, lang.code());
        }
        if let Some(doc) = window().and_then(|w| w.document()) {
            if let Some(el) = doc.document_element() {
                let _ = el.set_attribute("lang", lang.code());
            }
        }
    }

    /// Flip between the two supported languages.
    pub fn toggle(&self) {
        let next = match self.lang.get_untracked() {
            Language::En => Language::Vi,
            Language::Vi => Language::En,
        };
        self.set(next);
    }
}

/// Read the persisted language from localStorage, defaulting to English.
fn load_language() -> Language {
    window()
        .and_then(|w| w.local_storage().ok().flatten())
        .and_then(|s| s.get_item(LANG_KEY).ok().flatten())
        .and_then(|c| Language::from_code(&c))
        .unwrap_or(Language::En)
}

/// Install the language context and return it. Call once, near the app root.
pub fn provide_i18n() -> I18nContext {
    let ctx = I18nContext {
        lang: RwSignal::new(load_language()),
    };
    // Reflect the initial choice onto <html lang> for a11y / correctness.
    if let Some(doc) = window().and_then(|w| w.document()) {
        if let Some(el) = doc.document_element() {
            let _ = el.set_attribute("lang", ctx.lang.get_untracked().code());
        }
    }
    provide_context(ctx);
    ctx
}

/// Convenience accessor: fetch the `I18nContext` from context.
pub fn use_i18n() -> I18nContext {
    use_context::<I18nContext>().expect("I18nContext must be provided")
}

